function outlookForTicker(item) {
  if (item.setupType === "model_rebound_watch") return "Rebound Watch";
  if (item.setupTags?.includes("Not Momentum Confirmed")) return "Not Momentum";
  const percentile = Number(item.sp500Percentile ?? item.modelPercentile ?? 0);
  const riskCount = item.riskFlags?.length || 0;
  if (percentile >= 80 && riskCount <= 1 && item.above50 && item.above200) return "Favorable";
  if (percentile >= 45 && riskCount <= 2) return "Mixed";
  return "Weak";
}

function tickerNarrative(item) {
  const rank = item.sp500Rank ? `#${item.sp500Rank} of ${item.sp500UniverseCount}` : `#${item.modelRank} of ${item.modelUniverseCount}`;
  const trend = item.above50 && item.above200 ? "above both 50-day and 200-day trend lines" : item.above200 ? "above the 200-day trend line but missing shorter-term confirmation" : "below at least one major trend line";
  const relative = Number.isFinite(Number(item.relativeReturn60VsSpy)) ? `${pct(item.relativeReturn60VsSpy)} over 60 days versus SPY` : "relative-strength data is unavailable";
  const activation = item.setupType === "model_rebound_watch" && hasNumericValue(item.reboundActivationPrice)
    ? ` Rebound activation requires a close above ${money(item.reboundActivationPrice)} within ${item.reboundActivationWindowDays || 5} trading days.`
    : "";
  const setup = item.setupType === "model_rebound_watch"
    ? " This is a model rebound watch, not a confirmed momentum setup."
    : "";
  return `${item.symbol} ranks ${rank} versus the S&P 500 reference universe, with ${relative}; it is ${trend}.${setup}${activation}`;
}

function money(value) {
  if (!Number.isFinite(Number(value))) return "n/a";
  return Number(value).toLocaleString("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: Number(value) > 100 ? 2 : 2
  });
}

function hasNumericValue(value) {
  return value !== null && value !== undefined && value !== "" && Number.isFinite(Number(value));
}

function stopSellForSymbol(symbol) {
  const direct = (state.snapshot.recommendations || []).find((item) => item.symbol === symbol && hasNumericValue(item.stopSellPrice));
  if (direct) return direct;
  return (state.snapshot.opportunities || []).find(
    (item) => item.symbol === symbol && hasNumericValue(item.stopSellPrice)
  );
}

function stopSellChip(item) {
  const stop = hasNumericValue(item?.stopSellPrice) ? item : stopSellForSymbol(item?.symbol);
  if (!stop || !hasNumericValue(stop.stopSellPrice)) return "";
  const distance = hasNumericValue(stop.stopSellDistancePct) ? ` · ${pct(stop.stopSellDistancePct)}` : "";
  return `<span class="stop-chip" title="Exit on end-of-day close below stop">Stop: ${money(stop.stopSellPrice)}${distance}</span>`;
}

function activationChip(item) {
  if (item?.setupType !== "model_rebound_watch" || !hasNumericValue(item.reboundActivationPrice)) return "";
  const windowDays = item.reboundActivationWindowDays || 5;
  return `<span class="stop-chip activation-chip" title="Requires an end-of-day close above this level within ${esc(windowDays)} trading days">Activation: ${money(item.reboundActivationPrice)}</span>`;
}

function opportunitySetupClass(item) {
  if (item?.setupType === "momentum_confirmed") return "momentum-confirmed";
  if (item?.setupType === "model_rebound_watch") return "rebound-watch";
  if (item?.setupTags?.includes("Not Momentum Confirmed")) return "not-momentum-confirmed";
  return "model-ranked";
}

function opportunitySetupTitle(item) {
  if (item?.setupType === "momentum_confirmed") return "Momentum confirmed";
  if (item?.setupType === "model_rebound_watch") return "Watch only";
  if (item?.setupTags?.includes("Not Momentum Confirmed")) return "Trend not confirmed";
  return "Model ranked";
}

function opportunitySetupRead(item) {
  const setup = opportunitySetupClass(item);
  if (setup === "momentum-confirmed") {
    return [
      hasNumericValue(item.return20) ? `${pct(item.return20)} 20D` : null,
      hasNumericValue(item.return60) ? `${pct(item.return60)} 60D` : null,
      hasNumericValue(item.relativeReturn60VsSpy) ? `${pct(item.relativeReturn60VsSpy)} vs SPY` : null
    ].filter(Boolean).join(" · ");
  }

  if (setup === "rebound-watch") {
    return [
      hasNumericValue(item.relativeReturn60VsSpy) ? `${pct(item.relativeReturn60VsSpy)} vs SPY over 60D` : null,
      hasNumericValue(item.distanceTo52wHigh) ? `${pct(item.distanceTo52wHigh)} from 52W high` : null,
      hasNumericValue(item.volatility60d) ? `${displayReturnDecimal(item.volatility60d)} 60D daily vol` : null
    ].filter(Boolean).join(" · ");
  }

  return [
    item.above50 ? "Above 50D" : "Below 50D",
    item.above200 ? "Above 200D" : "Below 200D",
    hasNumericValue(item.relativeReturn60VsSpy) ? `${pct(item.relativeReturn60VsSpy)} vs SPY` : null
  ].filter(Boolean).join(" · ");
}

function opportunitySetupCallout(item) {
  const setup = opportunitySetupClass(item);
  const title = opportunitySetupTitle(item);
  const read = opportunitySetupRead(item);
  const riskFlags = (item.riskFlags || []).slice(0, 3).join(" · ");
  const activation = item.setupType === "model_rebound_watch" && hasNumericValue(item.reboundActivationPrice)
    ? `Needs an end-of-day close above ${money(item.reboundActivationPrice)} within ${item.reboundActivationWindowDays || 5} trading days before it is actionable.`
    : "";
  const body = setup === "rebound-watch"
    ? `Top-decile model score, but not confirmed momentum. ${activation}`
    : setup === "momentum-confirmed"
      ? "Top-decile model score with positive intermediate trend confirmation."
      : "Model score is notable, but the trend setup is incomplete.";
  return `
    <div class="setup-callout ${setup}">
      <strong>${esc(title)}</strong>
      <span>${esc(body)}</span>
      ${read ? `<small>${esc(read)}</small>` : ""}
      ${riskFlags ? `<small>Risk flags: ${esc(riskFlags)}</small>` : ""}
    </div>
  `;
}

function percentilePoint(value) {
  const number = Number(value);
  if (!Number.isFinite(number)) return null;
  return number <= 1 ? number * 100 : number;
}

function displayPercentilePoint(value) {
  const number = percentilePoint(value);
  if (!Number.isFinite(number)) return "n/a";
  return `${number.toFixed(0)}%`;
}

function isNotMomentumSetup(item) {
  const tags = [...(item?.setupTags || []), ...(item?.tacticalSetupTags || [])].join(" ");
  return /not momentum|activation pending|rebound watch/i.test(tags) || item?.setupType === "model_rebound_watch" || item?.tacticalSetupType === "model_rebound_watch";
}

function isMomentumConfirmedSetup(item) {
  const tags = [...(item?.setupTags || []), ...(item?.tacticalSetupTags || [])].join(" ");
  return /momentum confirmed/i.test(tags) && !isNotMomentumSetup(item);
}

